"""Generate the two readout policies this study compares, from one pinned source.

The candidate and its control must differ in exactly one thing, so both are
produced here from the same corrected source file by documented substitutions.
The pinned input is `_pinned_mom_c2.py`, git blob
d611bad0ddd624814e890468173e1d6a2a314b31, the corrected and optimised module the
earlier campaign qualified. `_pinned_mom_r1.py`, blob
eb9663c2ec61db28089e095ee7f636ce77f97e0f, is the corrected less-optimised path
kept as a semantic reference.

Two outputs:

  mom_renorm.py   the selected router probabilities are renormalised to sum to
                  one over the selected set. At top-1 that is one probability
                  divided by itself, which is identically one and passes no
                  gradient to the coefficient; at top-2 it is a real relative
                  mixture that does. This file serves both the top-1 control
                  and the top-2 candidate, so they cannot differ by anything
                  other than their configured k.

  mom_uniform.py  the selected set is chosen the same way, but the readout
                  coefficients are the constant one over k. Selection still
                  follows the router's scores, and the balancing objective
                  still reaches the router, but no gradient reaches the mixing
                  coefficient itself. This isolates the adaptive relative
                  weighting from the extra active banks that top-2 brings.

Both also gain an off-by-default capture hook so a test can read the
coefficients the forward actually applied rather than infer them.

  python3 make_modules.py
"""
import hashlib
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PINNED = os.path.join(HERE, "_pinned_mom_c2.py")

RENORM_SITE = "        routing_weights /= routing_weights.sum(dim=-1, keepdim=True)\n"

CAPTURE = (
    "        if getattr(self, '_capture_routing', False):\n"
    "            # off by default; a qualification test turns this on to read\n"
    "            # the coefficients the forward actually applied\n"
    "            self._last_routing_weights = routing_weights.detach().clone()\n"
    "            self._last_selected_memories = selected_memories.detach().clone()\n"
)

RENORM_NEW = (
    "        # Readout policy: renormalise the selected probabilities over the\n"
    "        # selected set. At k=1 this is p/p, identically one, and the\n"
    "        # coefficient carries no gradient. At k=2 it is a relative mixture\n"
    "        # of the two selected banks and does carry one.\n"
    "        routing_weights = routing_weights / routing_weights.sum(dim=-1, keepdim=True)\n"
) + CAPTURE

UNIFORM_NEW = (
    "        # Readout policy: constant coefficients of one over k. The selected\n"
    "        # set still comes from the router's scores and the balancing term\n"
    "        # still reaches the router, but the mixing coefficient itself is a\n"
    "        # constant, so no gradient flows through it. Detached on purpose.\n"
    "        routing_weights = torch.full_like(\n"
    "            routing_weights, 1.0 / float(self.topk)).detach()\n"
) + CAPTURE

HEADER = (
    '"""Generated by make_modules.py from _pinned_mom_c2.py. Do not edit.\n\n'
    'Readout policy: %s\n'
    'Pinned source sha256: %s\n'
    '"""\n'
)


def build(name, replacement, policy):
    src = io.open(PINNED, encoding="utf-8").read()
    if src.count(RENORM_SITE) != 1:
        raise SystemExit("expected exactly one readout site, found %d"
                         % src.count(RENORM_SITE))
    pinned_sha = hashlib.sha256(src.encode("utf-8")).hexdigest()
    out = HEADER % (policy, pinned_sha) + src.replace(RENORM_SITE, replacement)
    out = out + ("\n\nREADOUT_POLICY = %r\nPINNED_SOURCE_SHA256 = %r\n"
                 % (policy, pinned_sha))
    path = os.path.join(HERE, name)
    io.open(path, "w", encoding="utf-8").write(out)
    return path, hashlib.sha256(out.encode("utf-8")).hexdigest()


def build_from(pinned, name, replacement, policy):
    """Same substitution, applied to the less-optimised pinned source, so the
    top-2 path has a semantic reference that is not the same kernel layout."""
    global PINNED
    keep, PINNED = PINNED, pinned
    try:
        return build(name, replacement, policy)
    finally:
        PINNED = keep


if __name__ == "__main__":
    for name, repl, pol in (("mom_renorm.py", RENORM_NEW, "renormalized"),
                            ("mom_uniform.py", UNIFORM_NEW, "uniform")):
        p, h = build(name, repl, pol)
        print("%-22s %s  sha256 %s" % (os.path.basename(p), pol, h[:16]))
    R1 = os.path.join(HERE, "_pinned_mom_r1.py")
    for name, repl, pol in (("mom_renorm_ref.py", RENORM_NEW, "renormalized"),
                            ("mom_uniform_ref.py", UNIFORM_NEW, "uniform")):
        p, h = build_from(R1, name, repl, pol)
        print("%-22s %s  sha256 %s  (reference path)"
              % (os.path.basename(p), pol, h[:16]))
